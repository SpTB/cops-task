function isMatch = paramsMatchSettings(params, Nsc, Nor, Na)
%PARAMSMATCHSETTINGS Check whether cached texture params match settings.

isMatch = isstruct(params) && ...
    isfield(params, 'pixelStats') && isequal(size(params.pixelStats), [1 6]) && ...
    isfield(params, 'pixelLPStats') && isequal(size(params.pixelLPStats), [Nsc+1 2]) && ...
    isfield(params, 'autoCorrReal') && isequal(size(params.autoCorrReal), [Na Na Nsc+1]) && ...
    isfield(params, 'autoCorrMag') && isequal(size(params.autoCorrMag), [Na Na Nsc Nor]) && ...
    isfield(params, 'magMeans') && isequal(size(params.magMeans), [Nsc*Nor+2 1]) && ...
    isfield(params, 'cousinMagCorr') && isequal(size(params.cousinMagCorr), [Nor Nor Nsc+1]) && ...
    isfield(params, 'parentMagCorr') && isequal(size(params.parentMagCorr), [Nor Nor Nsc]) && ...
    isfield(params, 'cousinRealCorr') && isequal(size(params.cousinRealCorr), [2*Nor 2*Nor Nsc+1]) && ...
    isfield(params, 'parentRealCorr') && isequal(size(params.parentRealCorr), [2*Nor 2*Nor Nsc]) && ...
    isfield(params, 'varianceHPR') && isscalar(params.varianceHPR);

end
