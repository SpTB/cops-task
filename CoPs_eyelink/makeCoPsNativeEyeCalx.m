function eyeCal = makeCoPsNativeEyeCalx(setup, setupStatus, result, message, ptbTime)
% Calibration-shaped record for gaze already calibrated by the tracker.
% Legacy gain/offset fields are compatibility metadata, not an exported
% EyeLink calibration fit. Native gaze must bypass those fields.

eyeCal = makeCoPsMouseEyeCalx();
eyeCal.source = 'eyelink';
eyeCal.units = 'pixels';
eyeCal.modelLocation = 'tracker';
rect = double(setup.screenRect);
eyeCal.native = struct( ...
    'type', 'HV9', ...
    'setupStatus', setupStatus, ...
    'lastResult', result, ...
    'lastMessage', char(message), ...
    'savedAtPTB', ptbTime, ...
    'screenPixelCoords', [0 0 rect(3:4)-rect(1:2)-1], ...
    'monitorWidthCm', setup.monitorWidth, ...
    'viewingDistanceCm', setup.viewingDistance, ...
    'edfHostName', setup.el.edfFileName, ...
    'coefficientsExported', false);
end
