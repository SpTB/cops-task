function names = makeCoPsBenchRunnerx(outputDir)
% Build isolated, instrumented copies of the real trial loop for a bench run.
% Exact source anchors deliberately reject an incompatible future revision.

root = fileparts(mfilename('fullpath'));
if ~isfolder(outputDir), mkdir(outputDir); end
original = pwd;
cd(root);
restore = onCleanup(@() cd(original)); %#ok<NASGU>
[status, legacy] = system('git show c825eb7^:runTrialTaskCoPsx.m');
assert(status == 0, 'CoPsBench:MissingReference', ...
    'Cannot read the parent of the VBL commit from local Git history.');
current = fileread(fullfile(root, 'runTrialTaskCoPsx.m'));
names = {'runCoPsBenchLegacyTrialx', 'runCoPsBenchVblTrialx'};
sources = {legacy, current};
for k = 1:2
    text = sources{k};
    text = change(text, 'function [ex] = runTrialTaskCoPsx(', ...
        ['function [ex] = ' names{k} '(']);
    text = change(text, "trstart_Eyelink = Eyelink('TrackerTime');", ...
        'trstart_Eyelink = NaN; % Bench uses real ADC, no EyeLink connection.');
    text = change(text, 'sampleCoPsInputx( ...', 'sampleCoPsBenchInputx( ...');
    text = change(text, 'eyetimestep = 1/ex.setup.adc.Rate;', ...
        'eyetimestep = 1/ex.setup.hardwareBench.pollRateHz;');
    % Preserve the actual reward-on/refractory state even in output-off runs.
    text = strrep(text, "Datapixx('SetDoutValues',1);", ...
        "Datapixx('SetDoutValues',double(ex.setup.hardwareBench.rewardOutput));");
    text = change(text, '% PRE-ALLOCATE MEMORY FOR TIMING AND DATA', sprintf([ ...
        'ex.setup.hardwareBench.targetPositions = targPositions;\n' ...
        '%% PRE-ALLOCATE MEMORY FOR TIMING AND DATA']));
    text = change(text, '% Initialize input-related variables.', sprintf([ ...
        'benchPoll = nan(ceil(maxTrialDur * ex.setup.adc.Rate * 2), 14);\n' ...
        'benchPollN = 0; benchMarker = nan(frame_alloc_n, 1);\n' ...
        'benchOutputCleanup = onCleanup(@stopCoPsBenchOutputx); %%#ok<NASGU>\n' ...
        '%% Initialize input-related variables.']));
    text = change(text, 'trstart = GetSecs;  % start of trial time', sprintf([ ...
        'trstart = GetSecs;  %% start of trial time\n' ...
        'ex.setup.hardwareBench.trialStart = trstart;\n' ...
        'ex.setup.hardwareBench.goStart = NaN;']));
    text = change(text, 'time_stimOn = GetSecs - trstart;', sprintf([ ...
        'time_stimOn = GetSecs - trstart;\n' ...
        '            ex.setup.hardwareBench.goStart = time_stimOn + trstart;']));
    text = change(text, 'current_xy_abs = inputSample.position;', sprintf([ ...
        'current_xy_abs = inputSample.position;\n' ...
        '            benchPollN = benchPollN + 1;\n' ...
        '            benchPoll(benchPollN,:) = [inputSample.benchPoll reward_active current_step];']));
    oldMarker = sprintf([ ...
        'if GetSecs <= goSyncPulseEndTime\n' ...
        '                Screen(''FillRect'', ex.setup.window, spCol, spRects);\n' ...
        '                frameSyncPulseToSave = true;\n' ...
        '            end']);
    newMarker = sprintf([ ...
        'if state == ex.states.GO && isfinite(frameStepToSave)\n' ...
        '                benchElapsed = GetSecs - ex.setup.hardwareBench.goStart;\n' ...
        '                if benchElapsed < 0.10\n' ...
        '                    benchLevel = 1;\n' ...
        '                elseif benchElapsed < 0.15\n' ...
        '                    benchLevel = 0;\n' ...
        '                elseif strcmp(ex.setup.hardwareBench.markerMode, ''frame'')\n' ...
        '                    benchLevel = mod(fi, 2);\n' ...
        '                else\n' ...
        '                    benchLevel = mod(frameStepToSave, 2);\n' ...
        '                end\n' ...
        '                Screen(''FillRect'', ex.setup.window, 255 * benchLevel, spRects);\n' ...
        '                benchMarker(fi) = benchLevel;\n' ...
        '                frameSyncPulseToSave = logical(benchLevel);\n' ...
        '            else\n' ...
        '                Screen(''FillRect'', ex.setup.window, 0, spRects);\n' ...
        '                benchMarker(fi) = 0;\n' ...
        '            end']);
    text = change(text, oldMarker, newMarker);
    text = change(text, "if ~isMatlabWindowFocusedLocal()", ...
        'if false % Bench hotkeys also work while the projector has focus.');
    text = change(text, '[keyIsDown, secs, keyCode] = KbCheck;', sprintf([ ...
        '[keyIsDown, secs, keyCode] = KbCheck;\n' ...
        '    if keyIsDown && keyCode(KbName(''ESCAPE'')), ex.quit = 4; end\n' ...
        '    if ttime > ex.setup.hardwareBench.maxTrialSeconds\n' ...
        '        error(''CoPsBench:TrialTimeout'', ''Bench trial exceeded its time limit.'');\n' ...
        '    end']));
    text = change(text, '% blank screen at the end of trial', sprintf([ ...
        'stopCoPsBenchOutputx();\n' ...
        '%% blank screen at the end of trial']));
    text = change(text, sprintf('Screen(''Flip'', ex.setup.window);\n\n%% Store trial information'), ...
        sprintf('benchBlankVbl = Screen(''Flip'', ex.setup.window);\n\n%% Store trial information'));
    text = change(text, 'ex.Trials(ex.j).frameStateLookup = ex.states;', sprintf([ ...
        'ex.Trials(ex.j).frameStateLookup = ex.states;\n' ...
        'ex.Trials(ex.j).displayRefreshIntervalSec = Screen(''GetFlipInterval'', ex.setup.window);\n' ...
        'ex.Trials(ex.j).bench.polls = benchPoll(1:benchPollN,:);\n' ...
        'ex.Trials(ex.j).bench.pollColumns = {''startPTB'',''endPTB'',''framesRead'', ...\n' ...
        '    ''cumulativeSamples'',''inGO'',''gazeX'',''gazeY'',''idealStep'', ...\n' ...
        '    ''underflow'',''overflow'',''streamOverflows'',''streamUnderflows'', ...\n' ...
        '    ''rewardActive'',''behaviorStep''};\n' ...
        'ex.Trials(ex.j).bench.marker = benchMarker(1:fi-1);\n' ...
        'ex.Trials(ex.j).bench.blankVbl = benchBlankVbl;\n' ...
        'ex.Trials(ex.j).bench.config = rmfield(ex.setup.hardwareBench,''targetPositions'');']));
    writeText(fullfile(outputDir, [names{k} '.m']), text);
    writeText(fullfile(outputDir, sprintf('original_%d.txt', k)), sources{k});
end

adc = fileread(fullfile(root, 'checkEyex.m'));
adc = change(adc, 'function [pass_eye,trEye,lastEyePos] = checkEyex(', ...
    'function [pass_eye,trEye,lastEyePos,io] = readCoPsBenchAdcx(');
adc = change(adc, 'Datapixx RegWrRd', sprintf([ ...
    'io = struct(''underflow'',0,''overflow'',0,''status'',struct());\nDatapixx RegWrRd']));
adc = change(adc, "status = Datapixx ('GetAdcStatus') ;", sprintf([ ...
    'status = Datapixx (''GetAdcStatus'') ;\nio.status = status;']));
adc = change(adc, '[trEye.v(:, n+1:n+nBufFr) trEye.t(n+1:n+nBufFr)]=...', ...
    '[trEye.v(:, n+1:n+nBufFr) trEye.t(n+1:n+nBufFr) io.underflow io.overflow]=...');
adc = change(adc, "disp('in no new frames')", '% No console output in the timed bench loop.');
writeText(fullfile(outputDir, 'readCoPsBenchAdcx.m'), adc);
end

function text = change(text, before, after)
before = char(before); after = char(after);
assert(numel(strfind(text, before)) == 1, 'CoPsBench:SourceChanged', ...
    'Expected one source anchor: %s', before);
text = strrep(text, before, after);
end

function writeText(file, text)
fid = fopen(file, 'w');
assert(fid >= 0, 'CoPsBench:CannotWriteSource', 'Cannot write %s.', file);
closeFile = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, '%s', text);
end
